fn scratch(name: &str) -> PathBuf {
    let folder = std::env::temp_dir().join(format!("snisplit-icon-test-{}", std::process::id()));
    fs::create_dir_all(&folder).expect("a scratch folder");
    folder.join(name)
}

#[test]
fn one_image_icon_becomes_an_empty_entry_an_icon_entry_padded_to_four_bytes_and_a_group() {
    let ico = scratch("one.ico");
    let res = scratch("one.res");
    fs::write(&ico, ONE_IMAGE_ICO).expect("the icon is written");

    icon_resource::write_resource_file(&ico, &res).expect("a valid icon converts");

    let expected = [&EMPTY_ENTRY[..], &ICON_ENTRY[..], &GROUP_ENTRY[..]].concat();
    assert_eq!(fs::read(&res).expect("the resource file exists"), expected);
}

#[test]
fn a_cursor_file_is_refused() {
    let mut cursor = ONE_IMAGE_ICO;
    cursor[2] = 0x02;

    let refused =
        icon_resource::resource_file(&cursor).expect_err("type 2 is a cursor, not an icon");

    assert_eq!(refused.to_string(), "not an .ico file");
}

#[test]
fn an_image_that_runs_past_the_end_of_the_file_is_refused() {
    let mut truncated = ONE_IMAGE_ICO;
    truncated[14] = 0x04;

    let refused =
        icon_resource::resource_file(&truncated).expect_err("4 bytes at offset 22 need 26 bytes");

    assert_eq!(refused.to_string(), "an icon image lies outside the file");
}
